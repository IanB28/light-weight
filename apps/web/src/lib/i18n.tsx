const dictionaries: Record<Language, Record<TranslationKey, string>> = { es: ES, en: EN };
type Variables = Record<string, string | number>;

interface I18nValue {
  language: Language;
  locale: string;
  setLanguage: (language: Language) => void;
  t: (key: TranslationKey, variables?: Variables) => string;
}

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const { preferences, updatePreferences } = usePreferences();
  const language = preferences.language;

  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo<I18nValue>(() => ({
    language,
    locale: language === 'es' ? 'es-ES' : 'en-US',
    setLanguage: (next) => { updatePreferences({ language: next }); },
    t: (key, variables) => {
      let result = dictionaries[language][key];
      for (const [name, replacement] of Object.entries(variables || {})) {
        result = result.replaceAll(`{{${name}}}`, String(replacement));
      }
      return result;
    }
  }), [language, updatePreferences]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error('useI18n must be used within I18nProvider');
  return value;
}

export function useExerciseLabels() {
  const { t } = useI18n();
  return {
    muscleLabel: (muscle: MuscleGroup) => t(`muscle.${muscle}` as TranslationKey),
    equipmentLabel: (equipment: ExerciseCategory) => t(`equipment.${equipment}` as TranslationKey)
  };
}

